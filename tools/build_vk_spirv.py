FIXED_OUT = os.path.join(ROOT, "app/src/main/cpp/code/renderervulkan/vk_shaders_embedded.h")


def write_fixed():
    """the four fixed programs, in the header the 2D and first-light paths load"""
    blocks = []
    for src in FIXED:
        code = glslang(os.path.join(GLSL, src), "/tmp/vk_glsl/%s" % src.replace(".", "_"), 0, "frag")
        stem = src[len("vk_"):].replace(".", "_")
        guard = "VK_SHADER_%s_H" % stem.upper()
        words = struct.unpack("<%dI" % (len(code) // 4), code)
        rows = []
        for j in range(0, len(words), 4):
            part = ["0x%08xu," % w for w in words[j:j + 4]]
            if j + 4 >= len(words):
                part[-1] = part[-1].rstrip(",")
            rows.append("\t" + " ".join(part))
        blocks.append(
            "#ifndef %s\n#define %s\n\n"
            '#define VK_%s_SOURCE "renderervulkan/shaders/%s compiled by tools/build_vk_spirv.py -- do not edit"\n'
            "static const unsigned int vk_%s_spv[] = {\n%s\n};\n"
            "#define VK_%s_SPV_WORDS %du\n\n#endif\n"
            % (guard, guard, stem.upper(), src, stem, "\n".join(rows), stem.upper(), len(words)))
    with open(FIXED_OUT, "w") as fh:
        fh.write(FIXED_PREAMBLE.replace("@FINGERPRINT@", fingerprint()))
        fh.write("\n\n".join(blocks))
        fh.write("\n")
    print("wrote %s (%d fixed programs)" % (os.path.basename(FIXED_OUT), len(FIXED)))


def block_offsets(spv):
    """member offsets and names of the std140 block, out of the disassembly.

    OpMemberDecorate %block <i> Offset <n> gives the offset, and
    OpMemberName %block <i> "u_X" gives the name, so the two together are the
    layout the CPU side has to pack against.
    """
    dis = subprocess.run(["spirv-dis", spv], capture_output=True, text=True).stdout
    offsets = {}
    names = {}
    for m in re.finditer(r"OpMemberName\s+%(\w+)\s+(\d+)\s+\"(\w+)\"", dis):
        names[(m.group(1), int(m.group(2)))] = m.group(3)
    for m in re.finditer(r"OpMemberDecorate\s+%(\w+)\s+(\d+)\s+Offset\s+(\d+)", dis):
        key = (m.group(1), int(m.group(2)))
        offsets[key] = (names.get(key, "member%d" % key[1]), int(m.group(3)))
    # one block owns them all: take the struct with the most decorated members
    best = None
    for (sid, _mid) in offsets:
        n = sum(1 for (s, _m) in offsets if s == sid)
        if best is None or n > best[1]:
            best = (sid, n)
    if best is None:
        raise SystemExit("build_vk_spirv: no std140 block found in the SPIR-V")
    sid = best[0]
    rows = [(mid, offsets[(sid, mid)]) for (s, mid) in offsets if s == sid]
    rows.sort()
    return [r for _m, r in rows]


def main():
    if "--check" in sys.argv[1:]:
        raise SystemExit(check())

    masks = census_defines()
    print("shipped permutation census: %d distinct defines masks" % len(masks))

    ubo_src = os.path.join(GLSL, UBO_INC)
    block_text = open(ubo_src).read()

    modules = []
    ref_offsets = None
    workdir = "/tmp/vk_glsl"
    os.makedirs(workdir, exist_ok=True)

    measured = census_pairs()
    if measured:
        print("content census: %d measured (family, defines) pairs" % len(measured))

    for family, permuted in FAMILIES:
        fam_value = {"vk_stage": 0, "vk_2d": 0x01000000, "vk_dlight": 0x02000000,
                     "vk_sky": 0x04000000, "vk_sprite": 0x08000000,
                     "vk_sunflare": 0x10000000, "vk_shadow": 0x20000000,
                     "vk_wire": 0x40000000}.get(family, 0)
        pair_masks = [d & ~0xff000000 for (f, d) in measured if (f & 0xff000000) == fam_value]
        all_masks = sorted(set((masks if permuted else [0]) + pair_masks))
        for kind in ("vert", "frag"):
            src = os.path.join(workdir, "%s.%s" % (family, kind))
            open(src, "w").write(splice(os.path.join(GLSL, "%s.%s" % (family, kind))))
            for mask in all_masks:
                spv = os.path.join(workdir, "%s_%s_%06x.spv" % (family, kind.replace(".", "_"), mask))
                code = glslang(src, spv, mask, kind)
                modules.append((family, kind, mask, code))
                if family == "vk_stage" and kind == "vert" and ref_offsets is None:
                    ref_offsets = block_offsets(spv)
                    print("uniform block: %d members reflected from the SPIR-V" % len(ref_offsets))

    fam_const = {
        "vk_stage": "VK_SHADER_FAM_STAGE", "vk_2d": "VK_SHADER_FAM_2D",
        "vk_dlight": "VK_SHADER_FAM_DLIGHT", "vk_sky": "VK_SHADER_FAM_SKY",
        "vk_sprite": "VK_SHADER_FAM_SPRITE", "vk_sunflare": "VK_SHADER_FAM_SUNFLARE",
        "vk_shadow": "VK_SHADER_FAM_SHADOW", "vk_wire": "VK_SHADER_FAM_WIRE",
    }
    with open(OUT, "w") as fh:
        fh.write(HEADER_PREAMBLE.replace("@FINGERPRINT@", fingerprint()))
        fh.write("/* the std140 block's member offsets, read back out of the compiled SPIR-V,\n"
                 " * in the order the block declares them.  The CPU side packs the block at\n"
                 " * these. */\nenum {\n")
        for i, (name, off) in enumerate(ref_offsets):
            fh.write("\tVK_UBO_OFF_%s = %d%s\n" % (name.upper(), off, "," if i + 1 < len(ref_offsets) else ""))
        fh.write("};\n\n")
        for i, (family, kind, mask, code) in enumerate(modules):
            words = struct.unpack("<%dI" % (len(code) // 4), code)
            nm = "%s_%s_%06x" % (family, kind.replace(".", "_"), mask)
            fh.write("static const unsigned int %s[] = {\n" % nm)
            for j in range(0, len(words), 8):
                fh.write("\t" + ",".join("0x%08x" % w for w in words[j:j + 8]) + ",\n")
            fh.write("};\n\n")
        fh.write("static const vkShaderModuleDef_t vkShaderModules[] = {\n")
        for family, kind, mask, code in modules:
            fh.write("\t{ %s, 0x%06xu, %d, %s_%s_%06x, %d },\n"
                     % (fam_const[family], mask, 1 if kind == "frag" else 0,
                        family, kind.replace(".", "_"), mask, len(code) // 4))
        fh.write("};\n\n#define VK_SHADER_MODULE_COUNT %d\n\n" % len(modules))
        fh.write("#endif\n")

    print("wrote %s (%d modules)" % (os.path.basename(OUT), len(modules)))
    write_fixed()


if __name__ == "__main__":
    main()
