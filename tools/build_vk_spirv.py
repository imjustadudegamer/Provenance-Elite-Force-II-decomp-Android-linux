#!/usr/bin/env python3
"""Compile the Vulkan shade layer to SPIR-V and emit the embedded header.

The GLES3 twin validates every program permutation with glslangValidator at
build time (glsl/build_glsl.py) and compiles at run time; this module has no
runtime compiler, so the permutations are compiled here and embedded.

  1. the stage uniform block is spliced into every program at the marker
     tools/vk_shaders_from_gles3.py left.
  2. every distinct GLP_* defines bitmask the shipped census carries
     (renderergles3/tr_program_table.inc) is compiled, plus the other families
     with no defines at all -- a permutation that does not compile is a build
     failure, not a device run.
  3. the SPIR-V is disassembled once and the uniform block's member offsets are
     read back out of it, so the CPU-side packer is checked against the
     compiler's own layout rather than against a hand-written table.
  4. vk_shaders_embedded3d.h carries each module's SPIR-V keyed by family and
     defines, and the block offsets as a table the packer indexes.  The four
     fixed programs the 2D and first-light paths load go into
     vk_shaders_embedded.h the same way.

Usage: glslangValidator and spirv-dis must be on PATH.
       python3 tools/build_vk_spirv.py    (from the repository root)
"""

