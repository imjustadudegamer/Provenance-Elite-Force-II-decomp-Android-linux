def census_defines():
    """the distinct program-flag masks the shipped content uses"""
    text = open(TABLE).read()
    masks = set()
    for m in re.finditer(r"GLES3_PROGRAM_KEY\(([^)]*)\)", text):
        parts = [p.strip() for p in m.group(1).split(",")]
        if len(parts) >= 9:
            masks.add(int(parts[8], 0))
    # The texenv bits ride VK_StageProgram (OR'd in by VK_TexEnvForStage), so a
    # two-bundle pass asks for <its own mask> | <one texenv bit>.  Without the
    # cross here those variants are never compiled: every merged pass falls to
    # vk_stage.frag's MODULATE arm, the star dome draws stars-large times nebula
    # -- black -- and every world fx merge multiplies instead of adding.
    # GLES3_StageProgram does the same OR and its build seeds the masks
    # (glsl/build_glsl.py); here the module has to exist up front, so the seed
    # is the full cross over the census, not five hand-picked rows.
    TEXENV = (0x00200000, 0x00400000, 0x00800000)
    base = sorted(masks)
    for m in base:
        for t in TEXENV:
            masks.add(m | t)
    return sorted(masks)


TWIN_GLSL = os.path.join(ROOT, "app/src/main/cpp/code/renderergles3", "glsl")
CENSUS = os.path.join(GLSL, "vk_content_census.txt")


def census_pairs():
    """the (family, defines) pairs the shipped content asks for, measured.

    personal/scratch/vk_shader_census drives the module's own shader parser and
    its own stage-key arithmetic over the retail corpus; this reads what it
    measured.  A pair the table does not carry is a draw with no pipeline, so
    the census is a build input on the same footing as the sources: the digest
    covers it, and --check fails when it moves.
    """
    pairs = []
    if not os.path.exists(CENSUS):
        return pairs
    for line in open(CENSUS):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) < 2:
            continue
        pairs.append((int(parts[0], 16), int(parts[1], 16)))
    return pairs
TABLE_INC = os.path.join(ROOT, "app/src/main/cpp/code/renderergles3", "tr_program_table.inc")
DERIVER = os.path.join(ROOT, "tools", "vk_shaders_from_gles3.py")
FINGERPRINT_TAG = "//vk-spirv-fingerprint "


def fingerprint():
    """the digest of everything the embedded SPIR-V is a function of.

    The shader sources, the shared bodies they splice, the permutation census
    that picks the defines masks and the two tools themselves: a build that
    carries a header compiled from any other state of these is a lie, so the
    header records the digest and `--check` compares it.  This is the drift
    gate, and it needs no compiler to run.
    """
    inputs = []
    for dirpath, _dirs, files in os.walk(GLSL):
        for fn in files:
            inputs.append(os.path.join(dirpath, fn))
    inputs.append(os.path.join(TWIN_GLSL, "gles3_common.inc.glsl"))
    inputs.append(os.path.join(TWIN_GLSL, "gles3_clip.inc.glsl"))
    inputs.append(TABLE_INC)
    inputs.append(CENSUS)
    inputs.append(DERIVER)
    inputs.append(os.path.abspath(__file__))
    digest = hashlib.sha256()
    for path in sorted(inputs):
        digest.update(os.path.relpath(path, ROOT).encode())
        digest.update(b"\0")
        digest.update(open(path, "rb").read())
        digest.update(b"\0")
    return digest.hexdigest()


def recorded_fingerprint(path=OUT):
    for line in open(path):
        if line.startswith(FINGERPRINT_TAG):
            return line[len(FINGERPRINT_TAG):].strip()
    return None


def check():
    have = recorded_fingerprint()
    if have is None:
        sys.stderr.write("build_vk_spirv: %s carries no %s marker; regenerate with "
                         "python3 tools/build_vk_spirv.py\n" % (os.path.basename(OUT), FINGERPRINT_TAG.strip()))
        return 2
    want = fingerprint()
    if have != want:
        sys.stderr.write("build_vk_spirv: DRIFT -- %s was built from different shader sources\n"
                         "  recorded %s\n  current %s\n"
                         "  regenerate: python3 tools/build_vk_spirv.py\n"
                         % (os.path.basename(OUT), have, want))
        return 2
    print("build_vk_spirv: %s matches the shader sources (%d modules)"
          % (os.path.basename(OUT), recorded_module_count()))
    return 0


def recorded_module_count():
    for line in open(OUT):
        m = re.match(r"#define VK_SHADER_MODULE_COUNT (\d+)", line)
        if m:
            return int(m.group(1))
    return 0


def splice(path):
    """one program, made whole.

    The uniform block goes in straight after the #version line: it is a block
    of declarations, so any position ahead of the program's own code resolves.
    The shared bodies go where the twin's markers stand, so the generated file
    carries the directives its own build needs.
    """
    text = open(path).read()
    for name in ("VK_COMMON", "VK_CLIP"):
        marker = "//@@%s@@" % name
        if marker in text:
            inc = os.path.join(TWIN_GLSL, "gles3_%s.inc.glsl" % name.split("_")[1].lower())
            body = open(inc).read()
            body = re.sub(r"^/\*.*?\*/\s*", "", body, count=1, flags=re.S)
            # the include's scalar uniforms are already block members, so the
            # spliced copy must not declare them again
            body = re.sub(r"^\s*uniform\s+(?!sampler2D)[^;\n]+;[ \t]*(?:/\*.*?\*/)?[ \t]*$",
                          "", body, flags=re.M)
            # the twin names its helpers after itself; the program this body
            # is spliced into is VK-named
            body = re.sub(r"\bGLES3_", "VK_", body)
            body = re.sub(r"\bGLP_", "VKP_", body)
            text = text.replace(marker, body)
    # every sampler the program ends up with takes its fixed binding, whether
    # the program declared it or the shared library did
    for name, binding in (("u_Tex0", 1), ("u_Tex1", 2), ("u_WaveTable", 3)):
        text = re.sub(r"^\s*uniform\s+sampler2D\s+%s\s*;" % name,
                      "layout(set = 0, binding = %d) uniform sampler2D %s;" % (binding, name),
                      text, flags=re.M)
    # the block has to stand ahead of every use, so it goes in at the top of
    # the program rather than at a marker
    block = open(os.path.join(GLSL, UBO_INC)).read()
    text = text.replace(UBO_MARKER + "\n", "").replace(UBO_MARKER, "")
    lines = text.split("\n")
    for i, l in enumerate(lines):
        if l.startswith("#version"):
            lines.insert(i + 1, block)
            break
    return "\n".join(lines)


def glslang(source_path, out_path, defines, stage):
    cmd = ["glslangValidator", "-V", "--target-env", "vulkan1.0", "-o", out_path]
    for bit, name in VKP_NAMES:
        if defines & bit:
            cmd += ["-D%s=1" % name]
    cmd.append(source_path)
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stdout + r.stderr)
        raise SystemExit("build_vk_spirv: %s (defines 0x%x) failed" % (source_path, defines))
    return open(out_path, "rb").read()


