#!/usr/bin/env python3
"""The licence seam gate: every native source file must carry the notice its
provenance calls for, and no file may carry two conflicting ones.

Buckets (PROVENANCE.tsv, generated by tools/license_notices.py):

  gpl        id Tech 3 / OpenMoHAA lineage.  GNU GPL v2 or later, the ancestor's
             own banner kept verbatim, SPDX GPL-2.0-or-later.
  sdk        Ritual Elite Force II SDK.  The SDK's per-file banner kept verbatim
             (agreement section 2(k)), SPDX LicenseRef-Ritual-EF2-SDK.
  recon      rebuilt from the retail binaries, no source released.  The port
             asserts no copyright and grants no rights;
             SPDX LicenseRef-EF2-Retail-Reconstruction.
  vendored   a third party's own notice, restored verbatim and never relabelled.

A file may never carry a GNU GPL notice and a Ritual banner together: GPLv2
section 6 forbids the further restrictions the SDK agreement imposes, so one
file cannot be under both.

Exit: 0 green, 1 a check failed, 2 usage.
"""

import argparse
import os
import re
import sys

SRC_EXT = {".c", ".cc", ".cpp", ".cxx", ".h", ".hh", ".hpp", ".hxx", ".inl", ".inc"}
BUCKETS = {"gpl", "sdk", "recon", "vendored"}

GPL_MARK = re.compile(r"GNU General Public License")
RITUAL_MARK = re.compile(r"Ritual Entertainment")
RECON_MARK = re.compile(r"asserts no copyright")
SPDX_MARK = re.compile(r"SPDX-License-Identifier:\s*(\S+)")
LICENCE_MARK = re.compile(
    r"Copyright|License|Licence|GNU|GPL|public domain|All rights reserved|"
    r"Permission is hereby granted|SPDX-License-Identifier|may not be distributed",
    re.I,
)

GPL_SPDX = "GPL-2.0-or-later"
SDK_SPDX = "LicenseRef-Ritual-EF2-SDK"
RECON_SPDX = "LicenseRef-EF2-Retail-Reconstruction"


def read(path):
    with open(path, "r", encoding="utf-8", errors="surrogateescape", newline="") as fh:
        return fh.read()


def notice_region(text):
    """The file's notice: its first contiguous comment paragraph, returned only
    when that paragraph actually carries a licence marker or an SPDX id."""
    lines = text.splitlines()
    i = 0
    while i < len(lines) and lines[i].strip() == "":
        i += 1
    if i >= len(lines):
        return "", lines
    start = i
    in_block = False
    j = i
    while j < len(lines):
        s = lines[j].strip()
        if in_block:
            if "*/" in s:
                in_block = False
            j += 1
            continue
        if s == "":
            break
        if s.startswith("//"):
            j += 1
            continue
        if s.startswith("/*"):
            if "*/" not in s:
                in_block = True
            j += 1
            continue
        break
    region = "\n".join(lines[start:j])
    if LICENCE_MARK.search(region) or SPDX_MARK.search(region):
        return region, lines
    return "", lines


def ledger_rows(path):
    rows = {}
    with open(path, "r", encoding="utf-8", errors="surrogateescape") as fh:
        for line in fh:
            if line.startswith("#") or not line.strip():
                continue
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 3:
                continue
            rows[parts[0]] = (parts[1], parts[2])
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tree", required=True, help="the code/ directory")
    ap.add_argument("--ledger", required=True)
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()

    rows = ledger_rows(args.ledger)
    failures = []
    n = 0
    seen = set()

    for dirpath, dirnames, filenames in os.walk(args.tree):
        dirnames[:] = [d for d in dirnames if d != "thirdparty"]
        for fn in sorted(filenames):
            if os.path.splitext(fn)[1].lower() not in SRC_EXT:
                continue
            n += 1
            path = os.path.join(dirpath, fn)
            rel = os.path.relpath(path, args.tree)
            seen.add(rel)
            text = read(path)
            region, _lines = notice_region(text)
            row = rows.get(rel)
            if row is None:
                failures.append("%s: no PROVENANCE.tsv row" % rel)
                continue
            bucket = row[0]
            if bucket not in BUCKETS:
                failures.append("%s: unknown bucket %r" % (rel, bucket))
                continue
            if not region.strip():
                failures.append("%s: carries no notice" % rel)
                continue
            gpl = bool(GPL_MARK.search(region))
            ritual = bool(RITUAL_MARK.search(region))
            spdx = SPDX_MARK.search(region)
            spdx_id = spdx.group(1) if spdx else None
            if gpl and ritual:
                failures.append("%s: carries a GNU GPL notice and a Ritual banner together" % rel)
                continue
            if bucket == "gpl":
                if not gpl:
                    failures.append("%s: gpl bucket without a GNU GPL notice" % rel)
                if spdx_id != GPL_SPDX:
                    failures.append("%s: gpl bucket, SPDX %r (want %s)" % (rel, spdx_id, GPL_SPDX))
            elif bucket == "sdk":
                if not ritual:
                    failures.append("%s: sdk bucket without the Ritual banner" % rel)
                if gpl:
                    failures.append("%s: sdk bucket also claims the GNU GPL" % rel)
                if spdx_id != SDK_SPDX:
                    failures.append("%s: sdk bucket, SPDX %r (want %s)" % (rel, spdx_id, SDK_SPDX))
            elif bucket == "recon":
                if not RECON_MARK.search(region):
                    failures.append("%s: recon bucket without the no-rights statement" % rel)
                if gpl or ritual:
                    failures.append("%s: recon bucket claims GPL or Ritual provenance" % rel)
                if spdx_id != RECON_SPDX:
                    failures.append("%s: recon bucket, SPDX %r (want %s)" % (rel, spdx_id, RECON_SPDX))
            elif bucket == "vendored":
                if not LICENCE_MARK.search(region):
                    failures.append("%s: vendored bucket without its own notice" % rel)
                if spdx_id in (GPL_SPDX, SDK_SPDX, RECON_SPDX):
                    failures.append("%s: vendored bucket carries one of the project's SPDX ids" % rel)

    for rel in sorted(set(rows) - seen):
        failures.append("%s: PROVENANCE.tsv row for a file that does not exist" % rel)

    if not args.quiet:
        for f in failures:
            print("  FAIL  %s" % f)
    if failures:
        print("license_lint: RED -- %d failure(s) over %d source files" % (len(failures), n))
        return 1
    print("license_lint: GREEN -- %d source files, one notice each, no conflicting pair" % n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
