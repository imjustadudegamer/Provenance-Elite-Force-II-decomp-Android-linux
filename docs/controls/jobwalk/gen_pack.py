#!/usr/bin/env python3
"""Extract the shipping pack's texts from renderervulkan/vk_shade.c.

The jobwalk oracle must drive the SHIPPING pack body through the SHIPPING job
pool, not a paraphrase of either.  So this script lifts four texts out of the
source verbatim into jobwalk_pack_gen.c, and refuses (nonzero) if any of them
is gone: a body that was refactored away must break the control loudly instead
of letting it pass against a stale copy.

    VK_Stream_Pack        the per-element pack
    VK_Stream_PackRange   the JobPool range adapter
    vkPackCtx_t           the adapter's context
    VK_PACK_CHUNK         the range's minimum chunk

It also asserts the two things that make the change a change: the dispatch
goes through JobPool_ParallelRange, and the sequential loop it replaced is no
longer in RB_VBO_DrawTessArrays.  And it pins what the pack reads of the tess
store, which is what lets the oracle stand the engine's huge shaderCommands_t
in with a one-member stub.
"""
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else (
    "app/src/main/cpp/code/renderervulkan/vk_shade.c")
VPOH = sys.argv[2] if len(sys.argv) > 2 else (
    "app/src/main/cpp/code/renderervulkan/tr_vbo.h")
OUT = sys.argv[3] if len(sys.argv) > 3 else "jobwalk_pack_gen.c"


def fail(msg):
    sys.stderr.write("gen_pack: FAIL %s\n" % msg)
    raise SystemExit(1)


text = open(SRC, encoding="utf-8", errors="replace").read()


def block(start_pat, name, src=None):
    """The text of a definition, from its signature to its closing brace."""
    src = text if src is None else src
    m = re.search(start_pat, src)
    if not m:
        fail("no %s" % name)
    i = src.index("{", m.start())
    depth = 0
    for j in range(i, len(src)):
        if src[j] == "{":
            depth += 1
        elif src[j] == "}":
            depth -= 1
            if depth == 0:
                if src[m.start():m.start() + 7] == "typedef":
                    # a typedef's name (and a struct's semicolon) sits after
                    # the closing brace: take the statement's end, not the brace
                    k = src.index(";", j)
                    return src[m.start():k + 1]
                return src[m.start():j + 1]
    fail("unterminated %s" % name)


pack = block(r"static void VK_Stream_Pack\s*\(", "VK_Stream_Pack")
rng = block(r"static void VK_Stream_PackRange\s*\(", "VK_Stream_PackRange")
ctx = block(r"typedef struct\s*\{[^}]*\}\s*vkPackCtx_t\s*;", "vkPackCtx_t")
if not ctx.startswith("typedef"):
    fail("vkPackCtx_t extraction is not a typedef")

m = re.search(r"#define\s+VK_PACK_CHUNK\s+(\d+)", text)
if not m:
    fail("no VK_PACK_CHUNK define")
chunk = int(m.group(1))
if chunk < 1:
    fail("VK_PACK_CHUNK is %d" % chunk)

DISPATCH = ("JobPool_ParallelRange( input->numVertexes, VK_PACK_CHUNK, "
            "VK_Stream_PackRange, &packCtx );")
if DISPATCH not in text:
    fail("the pack is not dispatched through JobPool_ParallelRange")

i = text.index("void RB_VBO_DrawTessArrays")
j = text.index("\n}\n", i)
if re.search(r"for\s*\([^)]*\)[^{]*\{[^}]*VK_Stream_Pack\s*\(", text[i:j], re.S):
    fail("RB_VBO_DrawTessArrays still packs in a sequential loop")

# The element body's reads of the tess store, and nothing else: this is what
# the oracle's one-member shaderCommands_t stands in for.
reads = set(re.findall(r"input->(\w+)", pack))
if reads != {"xyz"}:
    fail("the pack reads %s of the tess store" % sorted(reads))

vbo = open(VPOH, encoding="utf-8", errors="replace").read()
streamblock = block(r"typedef struct\s*\{[^}]*\}\s*vkStreamVertex_t\s*;",
                    "vkStreamVertex_t (in %s)" % VPOH, vbo)

with open(OUT, "w", encoding="utf-8") as f:
    f.write("/* generated by gen_pack.py from %s and %s -- verbatim shipping"
            " text */\n" % (SRC, VPOH))
    f.write("#define JOBWALK_PACK_CHUNK %d\n\n" % chunk)
    f.write(streamblock + "\n\n")
    f.write(ctx + "\n\n")
    f.write(pack + "\n\n")
    f.write(rng + "\n")

print("gen_pack: chunk=%d pack=%dB range=%dB ctx=%dB vtx=%dB -> %s"
      % (chunk, len(pack), len(rng), len(ctx), len(streamblock), OUT))
