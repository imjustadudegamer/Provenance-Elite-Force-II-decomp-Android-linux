#!/usr/bin/env python3
"""Emit the rig inputs for the Event::FindEvent differential.

find_old.inc  -- the HEAD text of FindEvent/SortEventList/compareEvents, renamed
find_new.inc  -- the worktree text of the same three plus the hash helpers
event_names.inc -- the module's real registered event names, in file order
Everything is extracted verbatim; only the `Event::` qualifier is renamed.
"""
import re
import os
import subprocess
import json

WT = "/home/adam/Desktop/PORTS/EF2_Android_WIP/.claude/worktrees/r45-sdljava"
CPP = WT + "/app/src/main/cpp/code/fgame/listener.cpp"
REL = "app/src/main/cpp/code/fgame/listener.cpp"
OUT = "/home/adam/Desktop/PORTS/EF2_Android_WIP/scratch/r45sdljava"

FUNCS_NEW = [
    "int Event::FindEvent( const char *name )",
    "void Event::SortEventList( void )",
    "int Event::compareEvents( const void *arg1, const void *arg2 )",
    "long Event::generateHashValue( const char *name )",
    "void Event::ResetEventHash( void )",
    "void Event::BuildEventHash( void )",
]
FUNCS_OLD = FUNCS_NEW[:3]


def extract(text, sig):
    i = text.index(sig)
    j = text.index("{", i)
    depth = 0
    k = j
    while True:
        if text[k] == "{":
            depth += 1
        elif text[k] == "}":
            depth -= 1
            if depth == 0:
                break
        k += 1
    return text[i:k + 1]


HASH_BLOCK = """#define EVENT_HASH_SIZE\t\t4096
static int eventHashHead[ EVENT_HASH_SIZE ];"""


def emit(path, text, funcs, cls):
    parts = []
    if "BuildEventHash" in "".join(funcs):
        parts.append(HASH_BLOCK)
    for sig in funcs:
        parts.append(extract(text, sig))
    blob = "\n\n".join(parts).replace("Event::", cls + "::")
    blob = re.sub(r"^static int eventHashHead\[ EVENT_HASH_SIZE \];",
                  "static int eventHashHead[ EVENT_HASH_SIZE ];", blob, flags=re.M)
    open(path, "w").write("// generated by extract_find.py -- verbatim from %s\n%s\n" % (REL, blob))
    return blob


def main():
    old = subprocess.run(["git", "-C", WT, "show", "HEAD:" + REL],
                         capture_output=True, text=True, check=True).stdout
    new = open(CPP, encoding="utf-8").read()
    emit(OUT + "/find_old.inc", old, FUNCS_OLD, "EvOld")
    emit(OUT + "/find_new.inc", new, FUNCS_NEW, "EvNew")

    names = json.load(open(OUT + "/event_names.json"))["fgame"]
    seen = set()
    lines = ['static const char *g_registered[] = {']
    for n, f, l in names:
        esc = n.replace("\\", "\\\\").replace('"', '\\"')
        lines.append('    "%s",' % esc)
        seen.add(n.lower())
    lines.append("};")
    lines.append("#define G_REGISTERED_N %d" % len(names))
    open(OUT + "/event_names.inc", "w").write(
        "// generated from the fgame Event registrations in the worktree\n" + "\n".join(lines) + "\n")
    print("names %d, distinct(case-folded) %d" % (len(names), len(seen)))


main()
